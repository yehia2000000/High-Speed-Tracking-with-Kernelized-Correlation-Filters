#!/usr/bin/env python3
"""
Turn a tracking sequence into the two inputs of example/source/kcf_app.cpp.

The input folder is a sequence like the ones made by kcf_scalar/tools (OTB/VOT style):
  images.txt        one frame path per line (jpg/png/pgm; absolute, or relative to the folder)
  region.txt        box of frame 1: 8-number polygon or x,y,w,h
  groundtruth.txt   optional, x,y,w,h per frame

  --pgm OUT_DIR     for qemu-user: the frames as gray PGM files plus images.txt,
                    region.txt and groundtruth.txt. kcf_app_qemu reads this folder.
  --header OUT.hpp  for gem5: the first --frames frames compiled into a C++ header
                    (kcf_seq_width, kcf_seq_height, kcf_seq_frames, kcf_seq_init,
                    kcf_seq_gt, kcf_seq_data). Put it in images/ (on the gem5 include path).

Usage:
  python3 scripts/kcf_sequence.py ~/kcf_test/seqs/real_david --pgm images/kcf_seq_pgm
  python3 scripts/kcf_sequence.py ~/kcf_test/seqs/real_david --header images/kcf_seq.hpp --frames 3

Needs Pillow (pip install Pillow), like scripts/image_to_header.py.
"""

import argparse
import os
import re
import sys


def numbers(line):
    return [float(v) for v in re.split(r"[,\s]+", line.strip()) if v]


def to_xywh(v):
    if len(v) >= 8:
        xs, ys = v[0:8:2], v[1:8:2]
        return [min(xs), min(ys), max(xs) - min(xs), max(ys) - min(ys)]
    if len(v) >= 4:
        return v[:4]
    return None


def fmt(v):
    return f"{v:g}"


def cfloat(v):
    """C++ float literal: 129 -> 129.0f (129f is not valid C++)."""
    return f"{float(v)!r}f"


def main():
    try:
        from PIL import Image
    except ImportError:
        print("Pillow is required. Install it with: pip install Pillow", file=sys.stderr)
        sys.exit(1)

    p = argparse.ArgumentParser(description="Sequence -> PGM folder (qemu) and/or C++ header (gem5)")
    p.add_argument("seq_dir")
    p.add_argument("--pgm", help="output folder of PGM frames for kcf_app_qemu")
    p.add_argument("--header", help="output .hpp with the first --frames frames for kcf_app_gem5")
    p.add_argument("--frames", type=int, default=0,
                   help="number of frames (default: all for --pgm, 3 for --header)")
    p.add_argument("--name", default=None, help="sequence name printed by the app (default: folder name)")
    a = p.parse_args()
    if not a.pgm and not a.header:
        p.error("give --pgm and/or --header")

    seq = os.path.abspath(a.seq_dir)
    name = a.name or os.path.basename(seq.rstrip("/"))
    with open(os.path.join(seq, "images.txt")) as f:
        frames = [l.strip() for l in f if l.strip()]
    frames = [fr if os.path.isabs(fr) else os.path.join(seq, fr) for fr in frames]
    with open(os.path.join(seq, "region.txt")) as f:
        init = to_xywh(numbers(f.readline()))
    if init is None:
        sys.exit("region.txt: expected 4 or 8 numbers on the first line")
    gt = []
    gt_path = os.path.join(seq, "groundtruth.txt")
    if os.path.exists(gt_path):
        with open(gt_path) as f:
            gt = [b for b in (to_xywh(numbers(l)) for l in f if l.strip()) if b]

    def gray(path):
        return Image.open(path).convert("L")

    if a.pgm:
        n = a.frames or len(frames)
        out = os.path.abspath(a.pgm)
        os.makedirs(out, exist_ok=True)
        paths = []
        for i, fr in enumerate(frames[:n]):
            dst = os.path.join(out, f"{i + 1:04d}.pgm")
            gray(fr).save(dst)                       # binary P5, maxval 255
            paths.append(dst)
        with open(os.path.join(out, "images.txt"), "w") as f:
            f.write("\n".join(paths) + "\n")
        with open(os.path.join(out, "region.txt"), "w") as f:
            f.write(",".join(fmt(v) for v in init) + "\n")
        if gt:
            with open(os.path.join(out, "groundtruth.txt"), "w") as f:
                f.write("".join(",".join(fmt(v) for v in b) + "\n" for b in gt[:n]))
        print(f"{out}: {len(paths)} PGM frames" + (f", {min(n, len(gt))} ground-truth boxes" if gt else ""))

    if a.header:
        n = min(a.frames or 3, len(frames))
        imgs = [gray(fr) for fr in frames[:n]]
        w, h = imgs[0].size
        if any(im.size != (w, h) for im in imgs):
            sys.exit("all frames must have the same size")
        has_gt = 1 if len(gt) >= n else 0
        boxes = gt[:n] if has_gt else [[0, 0, 0, 0]] * n
        lines = []
        for im in imgs:
            data = im.tobytes()
            for i in range(0, len(data), 24):
                lines.append(", ".join(f"0x{b:02x}" for b in data[i:i + 24]))
        body = ",\n    ".join(lines)
        gt_rows = ",\n    ".join("{" + ", ".join(cfloat(v) for v in b) + "}" for b in boxes)
        hdr = f"""#pragma once
// Generated by scripts/kcf_sequence.py from {name}: frames 1..{n}, gray.
// Read by example/source/kcf_app.cpp on gem5 (no file I/O on bare metal).
#include <cstdint>

inline constexpr char kcf_seq_name[] = "{name}";
inline constexpr int kcf_seq_width  = {w};
inline constexpr int kcf_seq_height = {h};
inline constexpr int kcf_seq_frames = {n};
inline constexpr float kcf_seq_init[4] = {{{", ".join(cfloat(v) for v in init)}}};   // x, y, w, h of frame 1
inline constexpr int kcf_seq_has_gt = {has_gt};
inline constexpr float kcf_seq_gt[{n}][4] = {{
    {gt_rows}
}};
inline constexpr unsigned char kcf_seq_data[{n} * {w} * {h}] = {{
    {body}
}};
"""
        with open(a.header, "w", encoding="ascii") as f:
            f.write(hdr)
        kb = n * w * h / 1024
        print(f"{a.header}: {n} frames of {w} x {h} ({kb:.0f} KB of pixels in the image)")


if __name__ == "__main__":
    main()
